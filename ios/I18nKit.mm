#import "I18nKit.h"

#if __has_include("I18nKit/I18nKit-Swift.h")
#import "I18nKit/I18nKit-Swift.h"
#else
#import "I18nKit-Swift.h"
#endif

static NSString *const kLocaleChangedEvent = @"onLocaleChanged";

@implementation I18nKit {
  I18nKitImpl *_impl;
  BOOL _hasListeners;
}

RCT_EXPORT_MODULE()

/** Creates the Swift implementation and subscribes to system locale changes. */
- (instancetype)init
{
  if (self = [super init]) {
    _impl = [I18nKitImpl new];
    // Mirrors Android's ACTION_LOCALE_CHANGED: fires when the user changes
    // their system language/region while the app is running.
    [[NSNotificationCenter defaultCenter] addObserver:self
                                             selector:@selector(handleSystemLocaleChange)
                                                 name:NSCurrentLocaleDidChangeNotification
                                               object:nil];
  }
  return self;
}

/** Removes the notification observer. */
- (void)dealloc
{
  [[NSNotificationCenter defaultCenter] removeObserver:self];
}

/** @return NO: all work is cheap Foundation lookups, no UIKit, so no main-thread setup is needed. */
+ (BOOL)requiresMainQueueSetup
{
  return NO;
}

/** @return The single event this module emits: "onLocaleChanged". */
- (NSArray<NSString *> *)supportedEvents
{
  return @[ kLocaleChangedEvent ];
}

/** Called by RCTEventEmitter when the first JS listener attaches. */
- (void)startObserving
{
  _hasListeners = YES;
}

/** Called by RCTEventEmitter when the last JS listener detaches. */
- (void)stopObserving
{
  _hasListeners = NO;
}

/** Forwards NSCurrentLocaleDidChangeNotification to JS as "onLocaleChanged" (only while listeners exist). */
- (void)handleSystemLocaleChange
{
  if (_hasListeners) {
    [self sendEventWithName:kLocaleChangedEvent body:nil];
  }
}

// MARK: - Device locale detection

/** @return All preferred locales, most preferred first, as NativeLocaleInfo dictionaries. */
- (NSArray<NSDictionary *> *)getDeviceLocales
{
  return [_impl getDeviceLocales];
}

/** @return The most-preferred locale as a NativeLocaleInfo dictionary. */
- (NSDictionary *)getDeviceLocale
{
  return [_impl getDeviceLocale];
}

/** @return The ISO 3166-1 alpha-2 country code, or an empty string. */
- (NSString *)getCountry
{
  return [_impl getCountry];
}

/** @return The calendar identifier, e.g. "gregorian". */
- (NSString *)getCalendar
{
  return [_impl getCalendar];
}

/** @return The IANA time zone identifier, e.g. "Asia/Kolkata". */
- (NSString *)getTimeZone
{
  return [_impl getTimeZone];
}

/** @return A dictionary with decimalSeparator and groupingSeparator. */
- (NSDictionary *)getNumberFormatSettings
{
  return [_impl getNumberFormatSettings];
}

/** @return @YES for a 24-hour clock, @NO otherwise. */
- (NSNumber *)uses24HourClock
{
  return @([_impl uses24HourClock]);
}

/** @return @YES for the metric system, @NO otherwise. */
- (NSNumber *)usesMetricSystem
{
  return @([_impl usesMetricSystem]);
}

/**
 * @param languageCode A BCP-47 language code such as "ar".
 * @return @YES if the language is written right-to-left, @NO otherwise.
 */
- (NSNumber *)isRTLForLanguage:(NSString *)languageCode
{
  return @([_impl isRTLForLanguage:languageCode]);
}

// MARK: - App-level language override

/**
 * Persists the app language override for the next launch.
 *
 * @param languageTag A non-empty BCP-47 tag.
 * @param resolve Called with @NO (iOS always requires a restart).
 * @param reject Called with INVALID_LOCALE when the tag is empty or whitespace-only.
 */
- (void)setAppLanguage:(NSString *)languageTag
               resolve:(RCTPromiseResolveBlock)resolve
                reject:(RCTPromiseRejectBlock)reject
{
  NSString *trimmed = [languageTag stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceAndNewlineCharacterSet]];
  if (trimmed.length == 0) {
    reject(@"INVALID_LOCALE", @"setAppLanguage requires a non-empty BCP-47 language tag.", nil);
    return;
  }
  resolve(@([_impl setAppLanguage:languageTag]));
}

/** @return The persisted override tag, or an empty string. */
- (NSString *)getAppLanguage
{
  return [_impl getAppLanguage];
}

/**
 * @param params Initialisation parameters supplied by the TurboModule manager.
 * @return The JSI binding generated by codegen for this module.
 */
- (std::shared_ptr<facebook::react::TurboModule>)getTurboModule:
    (const facebook::react::ObjCTurboModule::InitParams &)params
{
  return std::make_shared<facebook::react::NativeI18nKitSpecJSI>(params);
}

@end
